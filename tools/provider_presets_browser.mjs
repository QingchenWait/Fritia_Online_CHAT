import assert from 'node:assert/strict';
import { CHAT_PROVIDER_PRESETS } from '../src/js/model_provider_presets.js';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ headless: true, ...(process.env.CHAT_TEST_BROWSER ? { executablePath: process.env.CHAT_TEST_BROWSER } : {}) });
const baseUrl = process.env.CHAT_TEST_URL || 'http://127.0.0.1:3000';
try {
  for (const viewport of [{ width: 1920, height: 1080 }, { width: 1280, height: 720 }, { width: 844, height: 390 }, { width: 390, height: 844 }, { width: 360, height: 640 }]) {
    const context = await browser.newContext({ viewport, serviceWorkers: 'block' });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.addInitScript(() => { localStorage.setItem('fritia_chat_onboarding_dismissed', '1'); window.testOpenedUrls = []; window.open = (...args) => { window.testOpenedUrls.push(args); return null; }; });
    await page.route('**/*', route => route.request().url().startsWith(baseUrl) ? route.continue() : route.abort());
    await page.goto(baseUrl);
    await page.waitForFunction(() => document.querySelector('.conversation-item'));
    const openSettings = detail => page.evaluate(detail => document.dispatchEvent(new CustomEvent('fritia-ui-open-panel', { detail: { id: 'settings-panel', settingsSection: 'model', modelTab: 'chat', ...detail } })), detail);
    const settings = () => page.evaluate(() => JSON.parse(localStorage.getItem('fritia-settings') || '{}'));
    await openSettings({});
    const add = page.locator(viewport.width <= 760 ? '#model-chat-add-mobile' : '#model-chat-add');
    const menu = page.locator('#chat-provider-preset-menu');
    const snapshot = await page.evaluate(() => localStorage.getItem('fritia_next_chat_store'));
    await add.click();
    assert.deepEqual(await menu.locator('button span').allTextContents(), ['DeepSeek', 'MiMO', 'Qwen', 'OpenAI', 'GLM', 'Kimi', '本地模型', '自定义']);
    const menuBounds = await menu.boundingBox();
    const buttonBounds = await add.boundingBox();
    assert.ok(Math.abs(menuBounds.y - buttonBounds.y - buttonBounds.height - 4) < 2, 'menu must sit directly below Add');
    assert.ok(menuBounds.x >= 0 && menuBounds.x + menuBounds.width <= viewport.width + 1);
    assert.ok(menuBounds.y + menuBounds.height <= viewport.height + 1);
    await page.waitForFunction(() => [...document.querySelectorAll('#chat-provider-preset-menu img')].every(image => image.complete && image.naturalWidth > 0));
    if (process.env.CHAT_TEST_SCREENSHOT_DIR && [1920, 390].includes(viewport.width)) await page.screenshot({ path: `${process.env.CHAT_TEST_SCREENSHOT_DIR}/provider-presets-${viewport.width}.png` });
    await page.keyboard.press('Escape');
    assert.equal(await menu.isVisible(), false);
    assert.equal(await add.getAttribute('aria-expanded'), 'false');
    for (const preset of CHAT_PROVIDER_PRESETS) {
      await add.click();
      await menu.locator(`[data-provider-preset="${preset.key}"]`).click();
      assert.equal(await menu.isVisible(), false);
      assert.equal(await page.inputValue('#chat-provider-id'), preset.id);
      assert.equal(await page.inputValue('#chat-provider-base-url'), preset.baseUrl);
      assert.equal(await page.inputValue('#chat-provider-model'), preset.model);
      assert.equal(await page.inputValue('#chat-provider-api-key'), '');
      const stored = (await settings()).chatProviders.find(item => item.id === preset.id);
      assert.equal(stored.model, preset.model);
      if (preset.website) {
        assert.equal(await page.isDisabled('#chat-provider-get-key'), false);
        await page.click('#chat-provider-get-key');
        const opened = await page.evaluate(() => window.testOpenedUrls.at(-1));
        assert.equal(opened[0], preset.website);
        assert.equal(opened[1], '_blank');
      }
    }
    await add.click();
    await menu.locator('[data-provider-preset="deepseek"]').click();
    assert.equal(await page.inputValue('#chat-provider-id'), 'DeepSeek-2');
    await page.fill('#chat-provider-base-url', 'https://unknown.test/v1');
    assert.equal(await page.isDisabled('#chat-provider-get-key'), true);
    await page.fill('#chat-provider-base-url', 'https://api.xiaomimimo.com/v1');
    await page.click('#chat-provider-get-key');
    assert.equal((await page.evaluate(() => window.testOpenedUrls.at(-1)))[0], 'https://platform.xiaomimimo.com/console/api-keys');
    assert.equal((await settings()).chatProviders.find(item => item.id === 'DeepSeek-2').baseUrl, 'https://api.deepseek.com/v1');
    await page.evaluate(() => { window.testNativeUrls = []; window.__TAURI__ = { core: { invoke: async (command, args) => window.testNativeUrls.push({ command, args }) } }; });
    const openedBeforeNative = await page.evaluate(() => window.testOpenedUrls.length);
    await page.click('#chat-provider-get-key');
    await page.waitForFunction(() => window.testNativeUrls.length === 1);
    assert.deepEqual(await page.evaluate(() => window.testNativeUrls[0]), { command: 'open_external_url', args: { url: 'https://platform.xiaomimimo.com/console/api-keys' } });
    assert.equal(await page.evaluate(() => window.testOpenedUrls.length), openedBeforeNative);
    await page.evaluate(() => { window.__TAURI_INTERNALS__ = { invoke: window.__TAURI__.core.invoke }; delete window.__TAURI__; });
    await page.click('#chat-provider-get-key');
    await page.waitForFunction(() => window.testNativeUrls.length === 2);
    await page.evaluate(() => { delete window.__TAURI_INTERNALS__; });
    await openSettings({ chatProviderId: 'MiMO' });
    await page.fill('#chat-provider-api-key', 'test-chat-key');
    await page.click('#model-chat-save');
    let saved = await settings();
    const ttsId = saved.defaultTtsProviderId;
    assert.equal(saved.ttsProviders.find(item => item.id === ttsId).apiKey, 'test-chat-key');
    await page.click('[data-model-tab="tts"]');
    await page.fill('#tts-provider-api-key', 'independent-tts-key');
    await page.click('#model-tts-save');
    await page.click('[data-model-tab="chat"]');
    assert.equal(await page.inputValue('#chat-provider-api-key'), 'test-chat-key');
    await page.click('#model-chat-save');
    assert.equal((await settings()).ttsProviders.find(item => item.id === ttsId).apiKey, 'independent-tts-key');
    await page.fill('#chat-provider-api-key', 'new-chat-key');
    await page.click('#settings-save');
    assert.equal((await settings()).ttsProviders.find(item => item.id === ttsId).apiKey, 'new-chat-key');
    await openSettings({ modelTab: 'tts' });
    const ttsCount = (await settings()).ttsProviders.length;
    await page.click(viewport.width <= 760 ? '#model-tts-add-mobile' : '#model-tts-add');
    assert.equal(await menu.isVisible(), false);
    assert.equal((await settings()).ttsProviders.length, ttsCount + 1);
    await openSettings({ chatProviderId: 'LM Studio' });
    assert.equal(await page.inputValue('#chat-provider-model'), '');
    await page.click('#model-chat-save');
    await page.reload();
    await page.waitForFunction(() => document.querySelector('.conversation-item'));
    await openSettings({ chatProviderId: 'LM Studio' });
    assert.equal(await page.inputValue('#chat-provider-id'), 'LM Studio');
    assert.equal(await page.inputValue('#chat-provider-model'), '');
    const inputBounds = await page.locator('#chat-provider-api-key').boundingBox();
    const getBounds = await page.locator('#chat-provider-get-key').boundingBox();
    assert.ok(getBounds.x >= inputBounds.x + inputBounds.width, 'Get button must be after input');
    assert.ok(getBounds.x + getBounds.width <= viewport.width, 'Key control must fit viewport');
    assert.equal(await page.evaluate(() => localStorage.getItem('fritia_next_chat_store')), snapshot);
    assert.deepEqual(errors, []);
    console.log(`PASS ${viewport.width}x${viewport.height}: all presets, live key links, native bridge, MiMO/TTS independence, local persistence, no unrelated store changes`);
    await context.close();
  }
} finally { await browser.close(); }
